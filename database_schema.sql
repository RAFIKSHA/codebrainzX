-- 1. Create Profiles table (linked to Django auth_user)
CREATE TABLE IF NOT EXISTS public.api_profile (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    role VARCHAR(10) NOT NULL DEFAULT 'student' CHECK (role IN ('student', 'admin')),
    avatar_url TEXT NULL,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
    user_id INTEGER UNIQUE NOT NULL
);

-- 2. Create Topics table
CREATE TABLE IF NOT EXISTS public.api_topic (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) UNIQUE NOT NULL,
    slug VARCHAR(255) UNIQUE NOT NULL,
    description TEXT NOT NULL,
    "order" INTEGER DEFAULT 0 NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

-- 3. Create Question Levels table
CREATE TABLE IF NOT EXISTS public.api_questionlevel (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    level VARCHAR(10) NOT NULL CHECK (level IN ('basic', 'easy', 'medium', 'hard')),
    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
    topic_id BIGINT REFERENCES public.api_topic(id) ON DELETE CASCADE,
    CONSTRAINT api_questionlevel_topic_id_level_unique UNIQUE (topic_id, level)
);

-- 4. Create Questions table
CREATE TABLE IF NOT EXISTS public.api_question (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(255) NOT NULL,
    slug VARCHAR(255) UNIQUE NOT NULL,
    statement TEXT NOT NULL,
    constraints TEXT NOT NULL,
    starter_code TEXT NOT NULL, -- JSON string mapping
    time_limit DOUBLE PRECISION DEFAULT 2.0 NOT NULL,
    memory_limit DOUBLE PRECISION DEFAULT 256.0 NOT NULL,
    is_published BOOLEAN DEFAULT TRUE NOT NULL,
    "order" INTEGER DEFAULT 0 NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
    topic_id BIGINT REFERENCES public.api_topic(id) ON DELETE CASCADE,
    level_id BIGINT REFERENCES public.api_questionlevel(id) ON DELETE CASCADE
);

-- 5. Create Test Cases table
CREATE TABLE IF NOT EXISTS public.api_testcase (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    input_data TEXT NOT NULL,
    expected_output TEXT NOT NULL,
    is_hidden BOOLEAN DEFAULT FALSE NOT NULL,
    question_id BIGINT REFERENCES public.api_question(id) ON DELETE CASCADE
);

-- 6. Create Languages table
CREATE TABLE IF NOT EXISTS public.api_language (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(50) UNIQUE NOT NULL,
    slug VARCHAR(20) UNIQUE NOT NULL,
    judge0_id INTEGER NOT NULL,
    extension VARCHAR(10) NOT NULL
);

-- 7. Create Submissions table
CREATE TABLE IF NOT EXISTS public.api_submission (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code TEXT NOT NULL,
    status VARCHAR(25) DEFAULT 'Pending' NOT NULL,
    error_message TEXT NULL,
    execution_time DOUBLE PRECISION NULL,
    memory_usage DOUBLE PRECISION NULL,
    passed_test_cases INTEGER DEFAULT 0 NOT NULL,
    total_test_cases INTEGER DEFAULT 0 NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
    language_id BIGINT REFERENCES public.api_language(id) ON DELETE SET NULL,
    question_id BIGINT REFERENCES public.api_question(id) ON DELETE CASCADE,
    user_id INTEGER NOT NULL
);

-- 8. Create User Progress table
CREATE TABLE IF NOT EXISTS public.api_userprogress (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    solved BOOLEAN DEFAULT FALSE NOT NULL,
    completed_at TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
    question_id BIGINT REFERENCES public.api_question(id) ON DELETE CASCADE,
    user_id INTEGER NOT NULL,
    CONSTRAINT api_userprogress_user_id_question_id_unique UNIQUE (user_id, question_id)
);

-- Indexes for performance
CREATE INDEX IF NOT EXISTS api_question_topic_id_idx ON public.api_question(topic_id);
CREATE INDEX IF NOT EXISTS api_question_level_id_idx ON public.api_question(level_id);
CREATE INDEX IF NOT EXISTS api_testcase_question_id_idx ON public.api_testcase(question_id);
CREATE INDEX IF NOT EXISTS api_submission_user_id_idx ON public.api_submission(user_id);
CREATE INDEX IF NOT EXISTS api_submission_question_id_idx ON public.api_submission(question_id);
CREATE INDEX IF NOT EXISTS api_userprogress_user_id_idx ON public.api_userprogress(user_id);
